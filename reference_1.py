import pandas as pd
import re

# 1. Загрузка данных
df_raw = pd.read_csv('miv_public_person_condemnation_1.csv')
df_correct = pd.read_csv('punishment_types.csv')

# 2. Настройка правил сопоставления
# ВАЖНО: Порядок имеет значение! Срабатывает первое найденное совпадение.
# Формат: (регулярное выражение, точное значение из punishment_types.csv)
mapping_rules = [
    (r'пожизненн', 'Пожизненное лишение свободы'),
    (r'смертн', 'Смертная казнь'),
    (r'условно-досрочн|освобожден.*из мест|освобожденные.*из мест', 'Условно-досрочно освобожденные'),
    (r'отсрочк|ст\.?\s*82', 'Отсрочка отбывания наказания'),
    (r'условн|испытательн|ст\.?\s*73', 'Условное осуждение'),
    (r'лишение специального', 'Лишение специального, воинского или почетного звания, классного чина и государственных наград'),
    (r'лишение права занимать|лишение права управлять|лишение права заниматься|лишением права|ззд', 'Лишение права занимать определенные должности или заниматься определенной деятельностью'),
    (r'обязательн', 'Обязательные работы'),
    (r'исправительн|замена исправ|ир-|ир\b', 'Исправительные работы'),
    (r'принудительн', 'Принудительные работы'),
    (r'ограничение по воен', 'Ограничение по военной службе'),
    (r'ограничение свободы', 'Ограничение свободы'),
    (r'лишение свободы|л/св|ик\b|колонии|поселении', 'Лишение свободы на определенный срок'),
    (r'штраф', 'Штраф'),
]

# Компилируем регулярные выражения для ускорения работы (игнорируем регистр)
compiled_rules = [(re.compile(pattern, re.IGNORECASE), target) for pattern, target in mapping_rules]

# 3. Функция сопоставления
def map_punishment(text):
    if pd.isna(text):
        return 'Не определено'

    text = str(text).lower()
    for pattern, target in compiled_rules:
        if pattern.search(text):
            return target

    return 'Не определено' # Если ни одно правило не сработало

# 4. Применение функции к датафрейму
print("Сопоставление значений...")
df_raw['correct_value'] = df_raw['value'].apply(map_punishment)

# 5. Анализ результатов
print("\n--- Распределение по видам наказаний ---")
print(df_raw['correct_value'].value_counts())

# Проверка на наличие нераспознанных значений
unmapped = df_raw[df_raw['correct_value'] == 'Не определено']
if not unmapped.empty:
    print(f"\n⚠️ Внимание! Не удалось сопоставить {len(unmapped)} строк:")
    print(unmapped['value'].unique()[:10]) # Выводим первые 10 примеров
else:
    print("\n✅ Все значения успешно сопоставлены!")

# 6. Сохранение результата в новый файл
df_raw.to_csv('miv_public_person_condemnation_mapped.csv', index=False, encoding='utf-8-sig')
print("\nРезультат сохранен в файл 'miv_public_person_condemnation_mapped.csv'")